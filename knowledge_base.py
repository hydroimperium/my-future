def retrieve_relevant_facts(user_data: UserHabitsInput, metrics: dict) -> list[dict]:
    """
    Формирует сбалансированный блок «Доказательная база»:
    1) Карточка лабораторных анализов (если прикреплен файл).
    2) Карточка онлайн-разбора дополнительных сведений (если заполнено текстовое поле).
    3) Главные факторы риска (отрицательные годы) И главные защитные факторы пользователя (положительные годы за отказ от курения, алкоголя, спортзал).
    """
    factors_years = metrics.get("factors_years", {})
    factors_ml = metrics.get("factors_microlives", {})
    lab_info = metrics.get("lab_summary_info")
    custom_info = metrics.get("custom_nuance_info")

    retrieved = []

    # 1. Карточка прикрепленного файла анализов
    if lab_info:
        abn = lab_info.get("detected_abnormalities", [])
        norm = lab_info.get("normal_markers", [])
        details_str = ""
        if abn:
            details_str = "Выявленные отклонения: " + "; ".join(abn[:4]) + ". "
        elif norm:
            details_str = "Показатели в пределах референса: " + ", ".join(norm[:4]) + ". "

        retrieved.append({
            "factor": "lab_analysis",
            "impact_years": lab_info.get("impact_years", 0.0),
            "impact_microlives": lab_info.get("impact_microlives", 0.0),
            "title": f"🧪 Лабораторный профиль ({lab_info.get('filename', 'Файл анализов')}) — ERFC / CKD-EPI / CTT",
            "fact": f"{details_str}{lab_info.get('clinical_summary', '')}",
            "action": lab_info.get("recommended_action", "Плановый контроль анализов в динамике.")
        })

    # 2. Карточка онлайн-разбора текстового поля
    if custom_info and custom_info.get("clinical_summary"):
        sources_list = custom_info.get("sources", [])
        sources_str = ""
        if sources_list:
            sources_str = " (Источники: " + "; ".join(s["title"] for s in sources_list[:2]) + ")"
        retrieved.append({
            "factor": "custom_nuance",
            "impact_years": custom_info.get("impact_years", 0.0),
            "impact_microlives": custom_info.get("impact_microlives", 0.0),
            "title": f"🌐 Онлайн-разбор: {custom_info.get('title', 'Дополнительные сведения')}",
            "fact": f"{custom_info['clinical_summary']}{sources_str}",
            "action": custom_info.get("recommended_action", "Плановое наблюдение у профильного врача.")
        })

    # 3. Негативные факторы риска (сортируем от самых больших потерь)
    negative_factors = [
        (name, val) for name, val in factors_years.items()
        if val < 0 and name in WHO_RISK_FACTS_DB
    ]
    negative_factors.sort(key=lambda x: x[1])

    for issue, val in negative_factors[:3]:
        item = WHO_RISK_FACTS_DB[issue]
        retrieved.append({
            "factor": issue,
            "impact_years": val,
            "impact_microlives": factors_ml.get(issue, 0.0),
            "title": item["title"],
            "fact": item["fact"],
            "action": item["action"]
        })

    # 4. Положительные (защитные) факторы пользователя (не курит, не пьет, спортзал, оптимальный вес)
    positive_factors = [
        (name, val) for name, val in factors_years.items()
        if val > 0 and name in WHO_PROTECTIVE_FACTS_DB
    ]
    positive_factors.sort(key=lambda x: x[1], reverse=True)

    # Всегда показываем минимум 2 главных плюса профиля (или до 4, если факторов риска нет)
    max_pos_to_show = 4 if len(negative_factors) == 0 else 2
    for pos_name, val in positive_factors[:max_pos_to_show]:
        item = WHO_PROTECTIVE_FACTS_DB[pos_name]
        retrieved.append({
            "factor": pos_name,
            "impact_years": val,
            "impact_microlives": factors_ml.get(pos_name, 0.0),
            "title": item["title"],
            "fact": item["fact"],
            "action": item["action"]
        })

    return retrieved[:6]
